//! Characterization tests for `extract_metadata` / `extract_models`: the non-3MF
//! guard, which slicer config wins, and the serialized metadata shape the
//! frontends receive.

mod common;

use std::{fs, io::Write};

use serde_json::json;
use zip::{ZipWriter, write::SimpleFileOptions};

use db::model::{Model, user::User};
use service::{AppState, extract_metadata, extract_models};

const PROJECT_SETTINGS: &str = r#"{
    "enable_support": "1",
    "filament_type": ["PLA", "PETG"],
    "layer_height": "0.2",
    "nozzle_diameter": ["0.4"]
}"#;

const SLIC3R_PE_CONFIG: &str = "\
; generated by PrusaSlicer 2.7.1
; filament_type = PETG
; layer_height = 0.15
; nozzle_diameter = 0.6
; support_material = 0
";

/// Writes a 3MF (zip) blob holding `entries` and returns a model pointing at it.
fn threemf_model(app_state: &AppState, sha256: &str, entries: &[(&str, &str)]) -> Model {
    let path = app_state.get_model_dir().join(format!("{sha256}.3mf"));
    let mut zip = ZipWriter::new(fs::File::create(path).unwrap());
    for (name, contents) in entries {
        zip.start_file(*name, SimpleFileOptions::default()).unwrap();
        zip.write_all(contents.as_bytes()).unwrap();
    }
    zip.finish().unwrap();

    common::model_with_blob(1, "Project", sha256, "3mf")
}

async fn metadata_json(app_state: &AppState, entries: &[(&str, &str)]) -> serde_json::Value {
    let model = threemf_model(app_state, "cccccccccccccccccccccccccccccccc", entries);
    let metadata = extract_metadata(&model, app_state).await.unwrap();

    serde_json::to_value(metadata).unwrap()
}

#[tokio::test]
async fn extract_metadata_and_models_reject_non_3mf_models() {
    let (_dir, app_state) = common::test_app_state().await;
    let model = common::model_with_blob(1, "Plain", "dddddddddddddddddddddddddddddddd", "stl");

    assert_eq!(
        common::internal_error_message(extract_metadata(&model, &app_state).await),
        "Model is not a 3MF file"
    );
    assert_eq!(
        common::internal_error_message(extract_models(&model, &User::default(), &app_state).await),
        "Model is not a 3MF file"
    );
}

#[tokio::test]
async fn extract_metadata_reads_bambu_project_settings() {
    let (_dir, app_state) = common::test_app_state().await;

    assert_eq!(
        metadata_json(
            &app_state,
            &[("Metadata/project_settings.config", PROJECT_SETTINGS)]
        )
        .await,
        json!({
            "nozzle_diameter": 0.4_f32,
            "layer_height": 0.2_f32,
            "material_type": "PLA, PETG",
            "supports_enabled": true,
        })
    );
}

#[tokio::test]
async fn extract_metadata_falls_back_to_prusaslicer_config() {
    let (_dir, app_state) = common::test_app_state().await;

    assert_eq!(
        metadata_json(
            &app_state,
            &[("Metadata/Slic3r_PE.config", SLIC3R_PE_CONFIG)]
        )
        .await,
        json!({
            "nozzle_diameter": 0.6_f32,
            "layer_height": 0.15_f32,
            "material_type": "PETG",
            "supports_enabled": false,
        })
    );
}

#[tokio::test]
async fn extract_metadata_prefers_project_settings_over_prusaslicer_config() {
    let (_dir, app_state) = common::test_app_state().await;

    assert_eq!(
        metadata_json(
            &app_state,
            &[
                ("Metadata/Slic3r_PE.config", SLIC3R_PE_CONFIG),
                ("Metadata/project_settings.config", PROJECT_SETTINGS),
            ]
        )
        .await,
        json!({
            "nozzle_diameter": 0.4_f32,
            "layer_height": 0.2_f32,
            "material_type": "PLA, PETG",
            "supports_enabled": true,
        })
    );
}

#[tokio::test]
async fn extract_metadata_without_slicer_config_fails() {
    let (_dir, app_state) = common::test_app_state().await;
    let model = threemf_model(
        &app_state,
        "eeeeeeeeeeeeeeeeeeeeeeeeeeeeeeee",
        &[("3D/3dmodel.model", "<model/>")],
    );

    assert_eq!(
        common::internal_error_message(extract_metadata(&model, &app_state).await),
        "Failed to extract metadata"
    );
}
